"""Пули інгредієнтів (200) та зілля (50) і рецепти.

Інгредієнт = категорія + прикметник: 20 категорій x 10 = 200 різних.
Зілля = ефект + рівень: 10 ефектів x 5 рівнів = 50 різних.
Рецепт зілля вимагає інгредієнти певних КАТЕГОРІЙ (по 1 штуці кожної),
тому з випадкових 5 інгредієнтів на день реально щось зварити.
"""
import random

CATEGORIES = [
    "Корінь", "Листок", "Гриб", "Квітка", "Ягода",
    "Кора", "Насіння", "Мох", "Шипшина", "Павутина",
    "Луска", "Перо", "Кістка", "Сльоза", "Пил",
    "Ікло", "Мед", "Смола", "Роса", "Плющ",
]

ADJECTIVES = [
    "місяця", "сонця", "туману", "криги", "вогню",
    "тіні", "золота", "кришталю", "пустки", "давнини",
]

EFFECTS = [
    "лікування", "сили", "швидкості", "невидимості", "захисту",
    "удачі", "мудрості", "стійкості", "нічного бачення", "підводного дихання",
]

GRADES = ["слабке", "звичайне", "сильне", "майстерне", "легендарне"]

# назва інгредієнта -> категорія
INGREDIENTS = {}
for _adj in ADJECTIVES:
    for _cat in CATEGORIES:
        INGREDIENTS[f"{_cat} {_adj}"] = _cat

# назва зілля -> {"recipe": [категорії], "price": ціна}
POTIONS = {}
_rng = random.Random(42)  # фіксоване зерно: рецепти однакові при кожному запуску
for _ei, _effect in enumerate(EFFECTS):
    for _gi, _grade in enumerate(GRADES):
        _name = f"Зілля {_effect} ({_grade})"
        _count = 2 if _gi < 2 else 3
        POTIONS[_name] = {
            "recipe": _rng.sample(CATEGORIES, _count),
            "price": 10 + (_ei % 4) * 5 + _gi * 20,
        }
